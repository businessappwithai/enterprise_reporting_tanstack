/**
 * Excel workbook for an Intelligent UI result.
 *
 * Laid out like the workbooks the report generator produces (a chart picture above
 * its data, a dark-blue header row, a Data sheet holding the full result), with one
 * sheet per view on the page. Every figure is `applySpec` over the executed rows, the
 * same function the page uses, so the file cannot disagree with the screen.
 */

import ExcelJS from "exceljs";
import { renderChartPng } from "@/lib/report-generation/chart-image";
import { applySpec } from "./apply-spec";
import { type ColumnKind, inferColumnKinds, toNumber, type ViewSpec } from "./spec";

const HEADER_FILL = "FF1F3864";
const HEADER_TEXT = "FFFFFFFF";
const MAX_COLUMN_WIDTH = 40;
const CHART_VIEWS = new Set<ViewSpec["view"]>(["bar", "line", "area", "pie"]);

export interface WorkbookInput {
  title: string;
  question: string;
  sql: string;
  dataSourceName: string;
  generatedBy: string;
  columns: string[];
  rows: Record<string, unknown>[];
  views: ViewSpec[];
  generatedAt?: Date;
}

/** A value ExcelJS can write: it rejects arbitrary objects, and Excel wants real numbers. */
function cellValue(value: unknown, kind: ColumnKind | undefined): ExcelJS.CellValue {
  if (value === null || value === undefined) return null;
  if (kind === "number") return toNumber(value) ?? String(value);
  if (value instanceof Date) return value;
  if (typeof value === "number" || typeof value === "string" || typeof value === "boolean") {
    return value;
  }
  return JSON.stringify(value);
}

function sheetName(base: string, used: Set<string>): string {
  const cleaned = base.replace(/[\\/*?:[\]]/g, "").trim() || "View";
  let name = cleaned.slice(0, 31);
  for (let n = 2; used.has(name.toLowerCase()); n++) {
    const suffix = ` (${n})`;
    name = `${cleaned.slice(0, 31 - suffix.length)}${suffix}`;
  }
  used.add(name.toLowerCase());
  return name;
}

/** Write a header row and data rows starting at `startRow`; returns the next free row. */
function writeTable(
  sheet: ExcelJS.Worksheet,
  startRow: number,
  columns: string[],
  rows: Record<string, unknown>[],
  kinds: Record<string, ColumnKind>
): number {
  const header = sheet.getRow(startRow);
  columns.forEach((name, i) => {
    const cell = header.getCell(i + 1);
    cell.value = name;
    cell.font = { bold: true, color: { argb: HEADER_TEXT } };
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: HEADER_FILL } };
  });
  header.commit();

  rows.forEach((row, r) => {
    const out = sheet.getRow(startRow + 1 + r);
    columns.forEach((name, i) => {
      out.getCell(i + 1).value = cellValue(row[name], kinds[name]);
    });
    out.commit();
  });

  columns.forEach((name, i) => {
    let width = name.length;
    for (const row of rows.slice(0, 200)) {
      const v = row[name];
      if (v !== null && v !== undefined) width = Math.max(width, String(v).length);
    }
    const column = sheet.getColumn(i + 1);
    column.width = Math.max(column.width ?? 0, Math.min(MAX_COLUMN_WIDTH, Math.max(12, width + 2)));
  });

  return startRow + 1 + rows.length;
}

export async function buildIntelligentUiWorkbook(input: WorkbookInput): Promise<Buffer> {
  const { columns, rows, views } = input;
  const generatedAt = input.generatedAt ?? new Date();
  const kinds = inferColumnKinds(columns, rows);

  const wb = new ExcelJS.Workbook();
  wb.creator = "Enterprise Reporting Platform";
  wb.created = generatedAt;

  const used = new Set<string>();

  const summary = wb.addWorksheet(sheetName("Summary", used));
  summary.getColumn(1).width = 18;
  summary.getColumn(2).width = 100;
  summary.getCell("A1").value = input.title;
  summary.getCell("A1").font = { bold: true, size: 14 };
  const facts: [string, string | number][] = [
    ["Question", input.question],
    ["Data source", input.dataSourceName],
    ["Generated by", input.generatedBy],
    ["Generated", generatedAt.toISOString()],
    ["Rows", rows.length],
    ["Views", views.length],
    ["SQL", input.sql],
  ];
  facts.forEach(([label, value], i) => {
    const row = i + 3;
    summary.getCell(`A${row}`).value = label;
    summary.getCell(`A${row}`).font = { bold: true };
    const cell = summary.getCell(`B${row}`);
    cell.value = value;
    cell.alignment = { wrapText: true, vertical: "top" };
  });

  for (const [index, spec] of views.entries()) {
    const applied = applySpec(columns, rows, spec);
    const title = spec.title ?? (spec.view === "kpi" ? (spec.y?.[0] ?? "Total") : `View ${index + 1}`);
    const sheet = wb.addWorksheet(sheetName(`${index + 1} ${title}`, used));

    sheet.getCell("A1").value = title;
    sheet.getCell("A1").font = { bold: true, size: 14 };

    if (spec.view === "kpi") {
      const label = spec.y?.[0] ?? "";
      sheet.getCell("A3").value = spec.aggregation ? `${spec.aggregation}(${label})` : label;
      sheet.getCell("A3").font = { bold: true };
      sheet.getCell("B3").value = cellValue(applied.rows[0]?.[label], "number");
      sheet.getCell("B3").font = { bold: true, size: 20 };
      sheet.getColumn(1).width = 28;
      sheet.getColumn(2).width = 20;
      continue;
    }

    let tableRow = 3;
    if (CHART_VIEWS.has(spec.view)) {
      const png = await renderChartPng(
        applied.rows,
        applied.columns,
        spec.view,
        spec.y ?? [],
        spec.x ? [spec.x] : []
      );
      if (png) {
        const imageId = wb.addImage({ buffer: png as unknown as ExcelJS.Buffer, extension: "png" });
        sheet.addImage(imageId, "A3:L30");
        tableRow = 32;
      } else {
        // The picture is the only thing that can go missing here, so say so in the
        // file itself; the table below carries the same figures.
        sheet.getCell("A3").value = "The chart image could not be rendered; the same figures follow.";
        sheet.getCell("A3").font = { italic: true, color: { argb: "FFC00000" } };
        tableRow = 5;
      }
    }

    const appliedKinds = inferColumnKinds(applied.columns, applied.rows);
    writeTable(sheet, tableRow, applied.columns, applied.rows, appliedKinds);
    if (applied.truncated) {
      sheet.getCell(`A${tableRow + applied.rows.length + 2}`).value =
        `Showing the first ${applied.rows.length} rows of this view.`;
    }
  }

  const data = wb.addWorksheet(sheetName("Data", used));
  writeTable(data, 1, columns, rows, kinds);
  data.views = [{ state: "frozen", ySplit: 1 }];

  return Buffer.from(await wb.xlsx.writeBuffer());
}
